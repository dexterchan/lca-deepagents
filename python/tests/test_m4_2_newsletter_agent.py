def _content(fd) -> str:
    # Same FileData handling as m4.2_run_newsletter.py.
    body = fd["content"] if isinstance(fd, dict) else fd
    return "\n".join(body) if isinstance(body, list) else body


@pytest.mark.skipif(
    not os.environ.get("RUN_LIVE_E2E"),
    reason="set RUN_LIVE_E2E=1 to run (spends LLM + Tavily credits)",
)
def test_live_run_produces_newsletter_and_research_archives():
    result = m42.agent.invoke(
        {"messages": [{"role": "user", "content": "Put together this week's newsletter."}]},
        config={
            "recursion_limit": 50,
            "configurable": {"thread_id": f"test-{uuid.uuid4().hex[:8]}"},
        },
    )
    files = result.get("files", {})
    assert "/output/newsletter.html" in files, f"state files: {sorted(files)}"
    html = _content(files["/output/newsletter.html"])
    assert "<!doctype html>" in html
    for genre in m42.TOP_GENRES:
        # markdown escapes & as &amp; in the rendered heading
        heading = f"<h2>{genre.replace('&', '&amp;')}</h2>"
        assert heading in html, f"newsletter missing section for {genre!r}"
        archive = f"/research/{genre}/sources.md"
        assert archive in files, f"missing research archive {archive!r}"

