def test_top_genres():
    assert m42.TOP_GENRES == ["Rock", "Latin", "Metal", "Alternative & Punk"]


def test_editor_prompt_names_every_genre_subagent_and_output_path():
    for genre in m42.TOP_GENRES:
        assert genre in m42.EDITOR_PROMPT
    assert "genre-researcher" in m42.EDITOR_PROMPT
    assert "markdown_to_html" in m42.EDITOR_PROMPT
    assert "/output/newsletter.html" in m42.EDITOR_PROMPT


def test_genre_researcher_is_scoped():
    r = m42.genre_researcher
    assert r["name"] == "genre-researcher"
    assert r["tools"] == [m42.internet_search]  # override — replaces inherited set
    assert r["model"] is cheap_model  # the cheaper model from models.py
    assert "sources.md" in r["system_prompt"]
    assert "/research/" in r["system_prompt"]
    assert "Do NOT summarize" in r["system_prompt"]


def test_researcher_permissions():
    rules = m42.research_permissions
    assert FilesystemPermission(
        operations=["read", "write"], paths=["/research/**"], mode="allow"
    ) in rules
    assert FilesystemPermission(
        operations=["write"], paths=["/**"], mode="deny"
    ) in rules


def test_editor_permissions():
    rules = m42.editor_permissions
    assert FilesystemPermission(
        operations=["write"], paths=["/research/**"], mode="deny"
    ) in rules
    assert all(rule.mode == "deny" for rule in rules)


def test_compiled_graph_wiring():
    assert {"model", "tools"} <= set(m42.agent.nodes)
    tools = m42.agent.nodes["tools"].bound.tools_by_name
    for name in (
        "markdown_to_html",  # the editor's own tool
        "task",  # subagent launcher
        "ls", "read_file", "write_file", "edit_file", "glob", "grep",  # file toolkit
    ):
        assert name in tools, f"missing main-agent tool: {name}"
    # internet_search must NOT be on the main agent — it is subagent-only.
    assert "internet_search" not in tools
    # the task tool advertises the genre-researcher subagent
    assert "genre-researcher" in tools["task"].description


