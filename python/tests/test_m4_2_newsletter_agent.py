# markdown_to_html — pure function, no mocks
# ---------------------------------------------------------------------------

SAMPLE_MD = (
    "# This Week in Music\n\n"
    "Intro sentence.\n\n"
    "## Rock\n\n"
    "Body text.\n\n"
    "| Artist | Release |\n"
    "| --- | --- |\n"
    "| Band | Album |\n"
)


def test_markdown_to_html_renders_headings_paragraphs_and_tables():
    html = m42.markdown_to_html.invoke({"markdown_text": SAMPLE_MD})
    assert "<h1>This Week in Music</h1>" in html
    assert "<h2>Rock</h2>" in html
    assert "<p>Intro sentence.</p>" in html
    assert "<table>" in html
    assert "<th>Artist</th>" in html and "<td>Album</td>" in html


def test_markdown_to_html_wraps_body_in_styled_page_template():
    html = m42.markdown_to_html.invoke({"markdown_text": "## Rock\n\nText."})
    assert html.startswith("<!doctype html>")
    assert "<style>" in html
    assert "<footer>Generated by a Deep Agents subagent team.</footer>" in html
    assert html.rstrip().endswith("</html>")


@pytest.mark.parametrize(
    ("title", "expected"),
    [
        pytest.param(None, "<title>This Week in Music</title>", id="default-title"),
        pytest.param("Weekly Digest", "<title>Weekly Digest</title>", id="custom-title"),
    ],
)
def test_markdown_to_html_title(title, expected):
    args = {"markdown_text": "## Rock\n\nText."}
    if title is not None:
        args["title"] = title
    html = m42.markdown_to_html.invoke(args)
    assert expected in html


@pytest.mark.parametrize(
    ("markdown_text", "forbidden"),
    [
        pytest.param(
            "## Rock\n\nNews <script>alert(1)</script> here.",
            ["<script>", "alert(1)"],
            id="script-tag",
        ),
        pytest.param(
            '## Rock\n\n<img src="x" onerror="alert(1)">',
            ["onerror", "alert(1)"],
            id="onerror-attribute",
        ),
        pytest.param(
            "## Rock\n\n[click](javascript:alert(1))",
            ["javascript:", "alert(1)"],
            id="javascript-href",
        ),
    ],
)
def test_markdown_to_html_sanitizes_untrusted_html(markdown_text, forbidden):
    html = m42.markdown_to_html.invoke({"markdown_text": markdown_text})
    for needle in forbidden:
        assert needle not in html


def test_markdown_to_html_keeps_safe_tags():
    html = m42.markdown_to_html.invoke(
        {"markdown_text": '## Rock\n\n<img src="x" onerror="alert(1)">'},
    )
    assert '<img src="x">' in html  # tag survives, only the bad attribute is stripped


